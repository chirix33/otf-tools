"""Tier B pipeline (started by run_tier_b.py inside the experiment venv).

For each model in order (Qwen, then Gemma; one model on the GPU at a time), for each system in priority order
(react_c, react_r, graphrag, recode):
  dev:    pilot20 smoke test -> up to 3 predefined candidate slots on all 308 pilot20 questions -> select by
          accuracy, then fewer total tokens, then the earlier slot -> freeze manifest + SPEC sec. 11 block;
  E1:     with a matching freeze manifest only: e1_d03, d06, d09, d12, d15 (694 questions).
Gemma starts only when every Qwen output validates as complete and its estimated workload (+20%) fits before the
deadline. At the deadline no new work is admitted and the delivery is finalised as explicitly partial.
Re-running the command resumes: answered questions, built indices and frozen selections are kept.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
import time
import traceback
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from clevrer_bench.data import load_items  # noqa: E402
from clevrer_bench.llm import get_model  # noqa: E402
from clevrer_bench.runner import load_predictions, run_system  # noqa: E402
from clevrer_bench.systems import load_system  # noqa: E402
from clevrer_bench.systems.tierb_common import dependency_versions, file_sha, stable_hash  # noqa: E402
from tierb.importer import E1_CORE, import_all  # noqa: E402
from tierb.serving import MockServer, ServingError, WSLServer  # noqa: E402

MODELS = ["qwen3.6-27b", "gemma-4-31b-think"]
SYSTEMS = ["react_c", "react_r", "graphrag", "recode"]          # priority order (plan sec. 3)
CDT = timezone(timedelta(hours=-5))                              # America/Chicago on Oct 27 2026 (CDT, UTC-5)
DEADLINE = datetime(2026, 10, 27, 18, 0, tzinfo=CDT)
PASSES = 3                   # passes over a document: later passes only retry errored questions
MAX_ATTEMPTS = 4             # errored (infrastructure) attempts per question before it is listed as failed
SMOKE_PER_TYPE = 2           # pilot smoke test: 2 questions of each type
EXTRACTION_FAIL_LIMIT = 0.10
DEV_MIN_COVERAGE = 0.95      # below this a candidate's dev run is broken, not just unlucky; missing ones score 0
MARGIN = 1.2
SERVER_STARTUP_S = 1800
SPEC_BEGIN, SPEC_END = "<!-- TIER-B-FREEZE:BEGIN (generated by tierb/pipeline.py) -->", "<!-- TIER-B-FREEZE:END -->"


class StageError(RuntimeError):
    pass


class Pipeline:
    def __init__(self, a):
        self.a = a
        self.runs = Path(a.runs).resolve()
        self.tb = self.runs / "tier_b"
        self.logs = self.tb / "logs"
        self.logs.mkdir(parents=True, exist_ok=True)
        self.deadline = datetime.fromisoformat(a.deadline) if a.deadline else DEADLINE
        self.server = (MockServer if a.mock_server else WSLServer)(self.logs, self.log)
        self.timing: dict = self._load("timing.json", {})

    # ------------------------------------------------------------------ bookkeeping
    def log(self, msg: str) -> None:
        line = f"{datetime.now().isoformat(timespec='seconds')}  {msg}"
        print(line, flush=True)
        with (self.logs / "pipeline.log").open("a", encoding="utf-8") as f:
            f.write(line + "\n")

    def event(self, **e) -> None:
        e = {"time": datetime.now().isoformat(timespec="seconds"), **e}
        with (self.tb / "events.jsonl").open("a", encoding="utf-8") as f:
            f.write(json.dumps(e, default=str) + "\n")
        status = {**self._load("status.json", {}), "updated": e["time"], "last_event": e, "pid": os.getpid(),
                  "deadline": self.deadline.isoformat()}
        self._save("status.json", status)

    def _load(self, name: str, default):
        p = self.tb / name
        return json.loads(p.read_text(encoding="utf-8")) if p.exists() else default

    def _save(self, name: str, obj) -> None:
        p = self.tb / name
        tmp = p.with_suffix(p.suffix + ".tmp")
        tmp.write_text(json.dumps(obj, indent=2, default=str), encoding="utf-8")
        tmp.replace(p)

    def now(self) -> datetime:
        return datetime.now(timezone.utc)

    def past_deadline(self) -> bool:
        return self.now() >= self.deadline

    def seconds_left(self) -> float:
        return (self.deadline - self.now()).total_seconds()

    # ------------------------------------------------------------------ stage 0-2
    def provenance(self, import_summary: dict, serving: dict) -> None:
        def git(*args):
            try:
                return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, timeout=30).stdout.strip()
            except Exception:
                return None
        prov = self._load("provenance.json", {})
        prov.setdefault("first_started", datetime.now().isoformat(timespec="seconds"))
        prov.update({"last_started": datetime.now().isoformat(timespec="seconds"),
                     "repo_commit": git("rev-parse", "HEAD"), "repo_branch": git("rev-parse", "--abbrev-ref", "HEAD"),
                     "local_changes": git("status", "--porcelain"), "python": sys.version,
                     "platform": platform.platform(), "dependencies": dependency_versions(),
                     "dependency_lock_sha256": file_sha(ROOT / "requirements-tierb.lock"),
                     "package": str(self.package), "imported": import_summary,
                     "serving": {**prov.get("serving", {}), **serving}, "deadline": self.deadline.isoformat(),
                     "models": self.a.models, "systems": self.a.systems})
        self._save("provenance.json", prov)

    def preflight_local(self) -> None:
        free = shutil.disk_usage(ROOT).free / 2 ** 30
        if free < 10:
            raise StageError(f"only {free:.1f} GB free on the repository's drive; free at least 10 GB")
        if not self.a.mock_server:
            from graphrag.index.operations.build_noun_graph.np_extractors.resource_loader import \
                download_if_not_exists
            for r in ("brown", "treebank", "averaged_perceptron_tagger_eng", "punkt", "punkt_tab"):
                download_if_not_exists(r)              # GraphRAG fast indexing (NLP) resources
        from clevrer_bench.systems.rag import RAGSystem
        r = RAGSystem.__new__(RAGSystem)
        import threading
        r._embed_lock, r._embedder = threading.Lock(), None
        r._embed(["warm-up"])                         # downloads bge-small (CPU) once
        for s in self.a.systems:                      # every adapter imports and builds
            load_system(s, self.a.models[0], **self.candidate_kwargs(s, self.a.models[0], 1, probe=True))
        self.log(f"[preflight] local checks passed ({free:.0f} GB free)")

    def find_package(self) -> Path:
        cands = [Path(self.a.package)] if self.a.package else [
            ROOT.parent.parent / "clevrer_docqa_package", ROOT.parent / "clevrer_docqa_package",
            ROOT / "clevrer_docqa_package", Path.cwd() / "clevrer_docqa_package"]
        for c in cands:
            if (c / "SHA256SUMS.txt").exists():
                return c.resolve()
        raise StageError("could not find clevrer_docqa_package (looked in: " + ", ".join(map(str, cands)) +
                         "). Pass --package <path to clevrer_docqa_package>.")

    # ------------------------------------------------------------------ candidates and freeze
    def candidate_kwargs(self, system: str, model: str, slot: int, probe: bool = False) -> dict:
        kw: dict = {"slot": slot}
        if system == "recode":
            kw["runs_root"] = str(self.runs)
        if system == "graphrag":
            dec = self._load(f"graphrag_decision__{model}.json", {})
            kw["index_method"] = dec.get("index_method", "standard")
            if slot == 3:
                tuned = self.tb / "graphrag_tuned" / model
                if probe and not (tuned / "tune_complete.json").exists():
                    kw["slot"] = 1                     # preflight probe only; the real slot 3 needs tuned prompts
                else:
                    kw["tuned_prompts_dir"] = str(tuned)
        return kw

    def freeze_path(self, system: str, model: str) -> Path:
        return self.tb / "freeze" / f"{system}__{model}.json"

    def frozen_system(self, system: str, model: str, out_name: str | None = None):
        p = self.freeze_path(system, model)
        if not p.exists():
            raise StageError(f"no freeze manifest for {system}/{model}: E1 may not start before dev selection")
        fz = json.loads(p.read_text(encoding="utf-8"))
        s = load_system(system, model, out_name=out_name or system, **fz["kwargs"])
        if s.config_hash() != fz["config_hash"]:
            raise StageError(f"{system}/{model}: configuration differs from its freeze manifest "
                             f"({s.config_hash()} != {fz['config_hash']}); prompts, dependencies, sampling or tool "
                             "definitions changed since the freeze. Restore them; E1 will not run on a changed setup.")
        return s, fz

    # ------------------------------------------------------------------ running one system over one document
    def run_doc(self, sysobj, model: str, doc: str, limit: int | None = None, per_type: int | None = None) -> dict:
        run_dir = self.runs / doc
        t0 = time.time()
        out_dir = run_dir / "systems" / f"{sysobj.name}__{model}"
        before = self._answered(out_dir, run_dir, limit, per_type)
        for p in range(1, PASSES + 1):
            if self.past_deadline():
                break
            self.server.ensure(model)
            self.event(event="pass_start", model=model, system=sysobj.name, doc=doc, pass_no=p)
            run_system(sysobj, run_dir, self.a.workers, limit=limit, per_type=per_type, max_attempts=MAX_ATTEMPTS,
                       should_stop=self.past_deadline, max_consecutive_errors=8)
            st = self._answered(out_dir, run_dir, limit, per_type)
            self.event(event="pass_end", model=model, system=sysobj.name, doc=doc, pass_no=p, **st)
            if st["answered"] == st["expected"]:
                break
        st = self._answered(out_dir, run_dir, limit, per_type)
        st["seconds"] = round(time.time() - t0, 1)
        st["new_answers"] = st["answered"] - before["answered"]
        return st

    def _answered(self, out_dir: Path, run_dir: Path, limit=None, per_type=None) -> dict:
        items = load_items(run_dir / "items.jsonl")
        if per_type:
            items = [it for t in sorted({i.question_type for i in items})
                     for it in [x for x in items if x.question_type == t][:per_type]]
        if limit:
            items = items[:limit]
        uids = {it.uid for it in items}
        rows = load_predictions(out_dir / "predictions.jsonl")
        ans = {r["uid"] for r in rows if "error" not in r} & uids
        return {"expected": len(uids), "answered": len(ans)}

    def setup_seconds(self, out_dir: Path) -> float:
        try:
            return float(json.loads((out_dir / "setup.json").read_text(encoding="utf-8")).get("latency_s") or 0)
        except (OSError, ValueError):
            return 0.0

    # ------------------------------------------------------------------ time estimates
    def spq(self, model: str, system: str) -> float | None:
        """Measured seconds per question (wall clock, with the configured workers) on pilot20."""
        t = self.timing.get(f"{model}/{system}")
        return t["seconds"] / t["questions"] if t and t["questions"] else None

    def record_timing(self, model: str, system: str, seconds: float, questions: int, setup_s: float) -> None:
        t = self.timing.setdefault(f"{model}/{system}", {"seconds": 0.0, "questions": 0, "setup_s": 0.0})
        t["seconds"] += seconds
        t["questions"] += questions
        t["setup_s"] = max(t["setup_s"], setup_s)
        self._save("timing.json", self.timing)

    def remaining_estimate(self, model: str, systems: list[str], current_spq: float, current_setup: float) -> float:
        """Seconds still needed for `model`: E1 of every listed system plus dev (smoke + one candidate) for the
        ones not frozen yet. Systems not measured yet use the current system's speed.
        ponytail: proxy speeds for unmeasured systems; replace with per-system pilot timings when available."""
        n_e1 = sum(len(load_items(self.runs / d / "items.jsonl")) for d in E1_CORE)
        n_pilot = len(load_items(self.runs / "pilot20" / "items.jsonl"))
        total = 0.0
        for s in systems:
            spq = self.spq(model, s) or current_spq
            setup = self.timing.get(f"{model}/{s}", {}).get("setup_s") or current_setup
            total += n_e1 * spq + len(E1_CORE) * setup
            if not self.freeze_path(s, model).exists():
                total += (n_pilot + 8) * spq + setup
        return total

    # ------------------------------------------------------------------ dev selection
    def dev(self, model: str, system: str, later: list[str]) -> None:
        if self.freeze_path(system, model).exists():
            self.frozen_system(system, model)          # validates the manifest against the current setup
            self.log(f"[dev] {system}/{model}: frozen selection found")
            return
        if system == "graphrag":
            self.graphrag_reliability(model)
        results = []
        for slot in (1, 2, 3):
            if self.past_deadline():
                break
            name = f"{system}_c{slot}"
            if slot > 1:
                spq = self.spq(model, system) or 60.0
                setup = self.timing.get(f"{model}/{system}", {}).get("setup_s", 0.0)
                need = (len(load_items(self.runs / "pilot20" / "items.jsonl")) * spq + setup
                        + self.remaining_estimate(model, [system] + later, spq, setup)) * MARGIN
                if need > self.seconds_left():
                    self.log(f"[dev] {system}/{model}: candidate slot {slot} not admitted (needs {need / 3600:.1f} h "
                             f"with margin, {self.seconds_left() / 3600:.1f} h left)")
                    self.event(event="candidate_skipped", model=model, system=system, slot=slot, need_s=need)
                    continue
            if system == "graphrag" and slot == 3:
                from clevrer_bench.systems.graphrag_system import tune_prompts
                self.server.ensure(model)
                self.log(f"[dev] graphrag/{model}: prompt auto-tuning on pilot20 (slot 3)")
                tuned = self.tb / "graphrag_tuned" / model
                tune_prompts(model, self.runs / "pilot20", tuned, tuned / "tune_calls.jsonl")
            kw = self.candidate_kwargs(system, model, slot)
            sysobj = load_system(system, model, out_name=name, **kw)
            out_dir = self.runs / "pilot20" / "systems" / f"{name}__{model}"
            if slot == 1:                              # end-to-end smoke test before the full dev evaluation
                st = self.run_doc(sysobj, model, "pilot20", per_type=self.a.smoke_per_type)
                bad = self.smoke_problems(out_dir, st)
                self.event(event="smoke", model=model, system=system, ok=not bad, problems=bad, **st)
                if bad:
                    raise StageError(f"smoke test failed for {system}/{model}: {bad}. See {out_dir}")
                self.log(f"[dev] {system}/{model}: smoke test passed ({st['answered']}/{st['expected']})")
            st = self.run_doc(sysobj, model, "pilot20", limit=self.a.dev_limit)
            if st["new_answers"]:
                self.record_timing(model, system, st["seconds"], st["new_answers"], self.setup_seconds(out_dir))
            if st["answered"] < st["expected"]:
                self.log(f"[dev] {system}/{model} slot {slot}: incomplete ({st['answered']}/{st['expected']})")
                if self.past_deadline():
                    break
                if st["answered"] < DEV_MIN_COVERAGE * st["expected"]:
                    raise StageError(f"dev evaluation of {name}/{model} answered only {st['answered']}/"
                                     f"{st['expected']} after {PASSES} passes; see {out_dir / 'attempts.jsonl'}")
            results.append(self.candidate_result(sysobj, model, slot, kw, out_dir))
            self.log(f"[dev] {system}/{model} slot {slot}: accuracy {results[-1]['accuracy']:.1f}% "
                     f"tokens {results[-1]['total_tokens']}")
        if not results:
            return
        best = sorted(results, key=lambda r: (-r["accuracy"], r["total_tokens"], r["slot"]))[0]
        self.freeze(model, system, best, results)

    def graphrag_reliability(self, model: str) -> None:
        """Pre-registered rule: standard indexing on pilot20; if >10% of chunks fail extraction, this model uses
        GraphRAG's documented fast indexing. Decided once per model, on pilot20 only, before any candidate."""
        name = f"graphrag_decision__{model}.json"
        if (self.tb / name).exists():
            return
        from clevrer_bench.systems.base import Document
        self.server.ensure(model)
        probe = load_system("graphrag", model, slot=1, out_name="graphrag_c1", index_method="standard")
        work = self.runs / "pilot20" / "systems" / f"graphrag_c1__{model}" / "work"
        work.mkdir(parents=True, exist_ok=True)
        self.log(f"[dev] graphrag/{model}: building the standard pilot20 index (extraction reliability check)")
        from clevrer_bench.systems.graphrag_system import IndexBuildError
        try:
            res = probe.setup(Document(self.runs / "pilot20" / "document.pdf",
                                       json.loads((self.runs / "pilot20" / "manifest.json").read_text(encoding="utf-8")),
                                       work))
            ex, usage, error = res.info["extraction"], res.usage.to_dict(), None
        except IndexBuildError as e:              # e.g. no entity extracted at all: every chunk failed
            ex, usage, error = e.extraction, probe.index_ledger.setup_usage()[0].to_dict(), str(e)
            if not ex["chunks"]:
                raise StageError(f"GraphRAG standard indexing on pilot20 failed before extraction: {e}")
            ex["failed_fraction"] = ex["failed_fraction"] if ex["failed_fraction"] is not None else 1.0
        method = "fast" if (ex["failed_fraction"] or 0) > EXTRACTION_FAIL_LIMIT else "standard"
        if error and method == "standard":
            raise StageError(f"GraphRAG standard indexing on pilot20 failed: {error}")
        dec = {"model": model, "index_method": method, "rule": f"fast if failed_fraction > {EXTRACTION_FAIL_LIMIT}",
               "standard_extraction": ex, "standard_index_setup_usage": usage, "standard_index_error": error,
               "decided": datetime.now().isoformat(timespec="seconds")}
        self._save(name, dec)
        self.event(event="graphrag_index_method", **dec)
        self.log(f"[dev] graphrag/{model}: {ex['failed_chunks']}/{ex['chunks']} chunks failed -> {method} indexing")
        if method == "fast":                           # slot-1 outputs of the standard probe are not used
            stale = self.runs / "pilot20" / "systems" / f"graphrag_c1__{model}"
            if (stale / "predictions.jsonl").exists():
                stale.rename(stale.with_name(stale.name + "__standard_probe"))

    def smoke_problems(self, out_dir: Path, st: dict) -> list[str]:
        bad = []
        if st["answered"] < st["expected"]:
            bad.append(f"only {st['answered']}/{st['expected']} answered")
        rows = [r for r in load_predictions(out_dir / "predictions.jsonl") if "error" not in r]
        if rows and all("parse_error" in r["parsed"] for r in rows):
            bad.append("every answer was unparseable")
        if rows and all((r.get("usage") or {}).get("llm_calls", 0) == 0 for r in rows):
            bad.append("no model calls were recorded")
        if not (out_dir / "setup.json").exists():
            bad.append("no setup.json")
        return bad

    def candidate_result(self, sysobj, model: str, slot: int, kw: dict, out_dir: Path) -> dict:
        items = load_items(self.runs / "pilot20" / "items.jsonl")
        if self.a.dev_limit:
            items = items[:self.a.dev_limit]
        uids = {it.uid for it in items}
        rows = {r["uid"]: r for r in load_predictions(out_dir / "predictions.jsonl") if "error" not in r}
        rows = {u: r for u, r in rows.items() if u in uids}
        setup = json.loads((out_dir / "setup.json").read_text(encoding="utf-8"))
        ans_tokens = sum(r["usage"]["total_tokens"] for r in rows.values())
        outcomes: dict = {}
        for r in rows.values():
            o = (r.get("trace") or {}).get("outcome") or ("parse_error" if "parse_error" in r["parsed"] else "ok")
            outcomes[o] = outcomes.get(o, 0) + 1
        # questions that failed every bounded retry count as wrong (accuracy over all dev questions)
        return {"slot": slot, "kwargs": kw, "out_dir": str(out_dir.relative_to(self.runs)), "n": len(rows),
                "missing": len(uids) - len(rows),
                "accuracy": 100.0 * sum(bool(r["score"]["question_correct"]) for r in rows.values()) / max(len(uids), 1),
                "answer_tokens": ans_tokens, "setup_tokens": setup["usage"]["total_tokens"],
                "total_tokens": ans_tokens + setup["usage"]["total_tokens"],
                "parse_errors": sum("parse_error" in r["parsed"] for r in rows.values()),
                "outcomes": outcomes, "config_hash": sysobj.config_hash(), "provenance": sysobj.provenance()}

    def freeze(self, model: str, system: str, best: dict, results: list[dict]) -> None:
        fz = {"system": system, "model": model, "selected_slot": best["slot"], "kwargs": best["kwargs"],
              "config_hash": best["config_hash"], "selection_rule": "accuracy, then fewer total tokens, then earlier slot",
              "candidates": [{k: v for k, v in r.items() if k != "provenance"} for r in results],
              "selected_provenance": best["provenance"], "model_spec": get_model(model).to_dict(),
              "dependencies": dependency_versions(), "frozen": datetime.now().isoformat(timespec="seconds"),
              "dev_set": "pilot20"}
        if system == "graphrag":
            fz["graphrag_decision"] = self._load(f"graphrag_decision__{model}.json", {})
            tuned = self.tb / "graphrag_tuned" / model / "tune_complete.json"
            if tuned.exists():
                fz["graphrag_prompt_tuning"] = json.loads(tuned.read_text(encoding="utf-8"))
        p = self.freeze_path(system, model)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(fz, indent=2, default=str), encoding="utf-8")
        self.event(event="frozen", model=model, system=system, slot=best["slot"], config_hash=best["config_hash"])
        self.log(f"[freeze] {system}/{model}: slot {best['slot']} ({best['accuracy']:.1f}%), hash {best['config_hash']}")
        self.write_spec()

    def write_spec(self) -> None:
        rows = ["", SPEC_BEGIN, "", "**Tier B frozen selections (written automatically before any E1 question; "
                "selection on pilot20 only):**", "",
                "| System | Model | Slot | Config hash | Candidates (slot: pilot20 accuracy, total tokens) | "
                "Indexing | Upstream |", "|---|---|---|---|---|---|---|"]
        for p in sorted((self.tb / "freeze").glob("*.json")):
            fz = json.loads(p.read_text(encoding="utf-8"))
            cands = "; ".join(f"{c['slot']}: {c['accuracy']:.1f}%, {c['total_tokens']:,}" for c in fz["candidates"])
            up = fz["selected_provenance"].get("upstream") or {}
            ups = (f"{up.get('package', up.get('repo', ''))} {up.get('version', '')} {str(up.get('commit', ''))[:12]}"
                   .strip() or "-")
            idx = fz["kwargs"].get("index_method", "-")
            rows.append(f"| {fz['system']} | {fz['model']} | {fz['selected_slot']} | `{fz['config_hash']}` | {cands} "
                        f"| {idx} | {ups} |")
        deps = dependency_versions()
        rows += ["", f"Dependencies: {', '.join(f'{k} {v}' for k, v in deps.items() if v)}. Lock: "
                 f"`requirements-tierb.lock` (sha256 {file_sha(ROOT / 'requirements-tierb.lock')[:16]}). "
                 "Shared caps: 12 model calls per question, 16,384 output tokens per call, frozen sampling from "
                 "`configs/models.json`. Machine-readable manifests: `runs/tier_b/freeze/`.", "", SPEC_END, ""]
        spec = ROOT / "SPEC.md"
        text = spec.read_text(encoding="utf-8")
        if SPEC_BEGIN in text:
            head, rest = text.split(SPEC_BEGIN, 1)
            tail = rest.split(SPEC_END, 1)[1] if SPEC_END in rest else ""
            text = head.rstrip("\n") + "\n" + "\n".join(rows[1:]) + tail.lstrip("\n")
        else:
            text = text.rstrip("\n") + "\n" + "\n".join(rows)
        spec.write_text(text, encoding="utf-8")

    # ------------------------------------------------------------------ E1
    def e1(self, model: str, system: str) -> None:
        sysobj, fz = self.frozen_system(system, model)
        for doc in E1_CORE:
            if self.past_deadline():
                return
            st = self.run_doc(sysobj, model, doc, limit=self.a.e1_limit)
            self.log(f"[e1] {system}/{model} {doc}: {st['answered']}/{st['expected']}")
            if st["new_answers"]:
                self.record_timing(model, system + "@e1", st["seconds"], st["new_answers"], 0.0)

    def validate(self, model: str) -> dict:
        """Per system and document: setup.json present and complete, exactly one prediction per expected uid."""
        out = {}
        for system in self.a.systems:
            for doc in E1_CORE:
                d = self.runs / doc / "systems" / f"{system}__{model}"
                items = load_items(self.runs / doc / "items.jsonl")
                if self.a.e1_limit:
                    items = items[:self.a.e1_limit]
                uids = [it.uid for it in items]
                rows = [r for r in load_predictions(d / "predictions.jsonl") if "error" not in r]
                seen = [r["uid"] for r in rows]
                setup = json.loads((d / "setup.json").read_text(encoding="utf-8")) if (d / "setup.json").exists() else None
                missing = sorted(set(uids) - set(seen))
                ok = (setup is not None and not missing and len(seen) == len(set(seen))
                      and set(seen) <= set(load_items_uids(self.runs / doc)))
                out[f"{system}/{doc}"] = {"ok": ok, "expected": len(uids), "answered": len(set(seen) & set(uids)),
                                          "missing": missing, "duplicates": len(seen) - len(set(seen)),
                                          "has_setup": setup is not None}
        return out

    # ------------------------------------------------------------------ delivery
    def deliver(self, partial_reason: str | None = None) -> dict:
        from clevrer_bench.report import make_report, make_split_report
        jobs, missing_jobs = [], []
        for model in self.a.models:
            val = self.validate(model)
            for system in self.a.systems:
                fz_p = self.freeze_path(system, model)
                fz = json.loads(fz_p.read_text(encoding="utf-8")) if fz_p.exists() else None
                for doc in E1_CORE:
                    v = val[f"{system}/{doc}"]
                    d = self.runs / doc / "systems" / f"{system}__{model}"
                    files = {f: file_sha(d / f) for f in ("predictions.jsonl", "setup.json") if (d / f).exists()}
                    job = {"model": model, "system": system, "document": doc, "folder": str(d.relative_to(self.runs)),
                           "complete": v["ok"], "expected": v["expected"], "answered": v["answered"],
                           "missing_uids": v["missing"], "duplicates": v["duplicates"], "sha256": files,
                           "config_hash": fz["config_hash"] if fz else None,
                           "selected_slot": fz["selected_slot"] if fz else None}
                    jobs.append(job)
                    if not v["ok"]:
                        missing_jobs.append({k: job[k] for k in ("model", "system", "document", "answered", "expected")})
        from clevrer_bench.systems.graphrag_system import graphrag_version
        from clevrer_bench.systems.recode_system import RECODE_COMMIT
        failures = self.failure_summary()
        manifest = {"generated": datetime.now().isoformat(timespec="seconds"),
                    "status": "complete" if not missing_jobs else "partial",
                    "partial_reason": partial_reason if missing_jobs else None,
                    "deadline": self.deadline.isoformat(), "expected_jobs": len(jobs),
                    "complete_jobs": sum(j["complete"] for j in jobs), "missing_jobs": missing_jobs,
                    "expected_predictions": sum(j["expected"] for j in jobs),
                    "actual_predictions": sum(j["answered"] for j in jobs),
                    "graphrag": graphrag_version(), "recode": {"repo": "FoundationAgents/ReCode", "commit": RECODE_COMMIT},
                    "freeze_manifests": sorted(str(p.relative_to(self.runs)) for p in (self.tb / "freeze").glob("*.json")),
                    "failures": failures, "jobs": jobs}
        self._save("delivery_manifest.json", manifest)
        names = [f"{s}__{m}" for m in self.a.models for s in self.a.systems]
        for doc in E1_CORE:
            have = [n for n in names if (self.runs / doc / "systems" / n / "setup.json").exists()
                    and (self.runs / doc / "systems" / n / "predictions.jsonl").exists()]
            if have:
                make_report(self.runs / doc, have)
        if any((self.runs / E1_CORE[0] / "systems" / n).exists() for n in names):
            make_split_report(self.runs, "e1", names)
        self.write_summary(manifest)
        self.log(f"[deliver] {manifest['status']}: {manifest['complete_jobs']}/{manifest['expected_jobs']} jobs, "
                 f"{manifest['actual_predictions']}/{manifest['expected_predictions']} predictions "
                 f"-> {self.tb / 'delivery_manifest.json'}")
        return manifest

    def failure_summary(self) -> dict:
        out = {}
        for model in self.a.models:
            for system in self.a.systems:
                c = {"answered": 0, "parse_errors": 0, "truncated": 0, "call_cap_exhausted": 0,
                     "usage_unknown_calls": 0, "errored_attempts": 0}
                for doc in E1_CORE:
                    d = self.runs / doc / "systems" / f"{system}__{model}"
                    for r in load_predictions(d / "predictions.jsonl"):
                        if "error" in r:
                            continue
                        tr = r.get("trace") or {}
                        c["answered"] += 1
                        c["parse_errors"] += "parse_error" in r["parsed"]
                        c["truncated"] += tr.get("finish_reason") == "length"
                        c["call_cap_exhausted"] += bool(tr.get("call_cap_exhausted"))
                        c["usage_unknown_calls"] += int(tr.get("usage_unknown_calls") or 0)
                    if (d / "attempts.jsonl").exists():
                        c["errored_attempts"] += len((d / "attempts.jsonl").read_text().splitlines())
                out[f"{system}__{model}"] = c
        return out

    def write_summary(self, m: dict) -> None:
        lines = [f"# Tier B delivery ({m['status']})", "", f"Generated {m['generated']}; deadline {m['deadline']}.",
                 f"Jobs complete: {m['complete_jobs']}/{m['expected_jobs']}; predictions "
                 f"{m['actual_predictions']}/{m['expected_predictions']}.", ""]
        if m["missing_jobs"]:
            lines += [f"**Partial delivery** ({m['partial_reason'] or 'incomplete jobs'}). Unfinished jobs:", "",
                      "| Model | System | Document | Answered |", "|---|---|---|---|"]
            lines += [f"| {j['model']} | {j['system']} | {j['document']} | {j['answered']}/{j['expected']} |"
                      for j in m["missing_jobs"]]
            lines.append("")
        lines += ["| System | Answered | Parse errors | Truncated | Call cap | Unknown-usage calls | Errored attempts |",
                  "|---|---|---|---|---|---|---|"]
        lines += [f"| {k} | {v['answered']} | {v['parse_errors']} | {v['truncated']} | {v['call_cap_exhausted']} | "
                  f"{v['usage_unknown_calls']} | {v['errored_attempts']} |" for k, v in m["failures"].items()]
        lines += ["", f"GraphRAG {m['graphrag']['version']} ({m['graphrag']['commit']}); ReCode "
                  f"{m['recode']['commit']}. Accuracy/cost reports: runs/e1_report.md and runs/e1_dXX/report.md."]
        (self.tb / "DELIVERY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # ------------------------------------------------------------------ main flow
    def gemma_admitted(self, first: str, model: str) -> bool:
        val = self.validate(first)
        if not all(v["ok"] for v in val.values()):
            self.log(f"[schedule] {model} not started: {first} outputs are not complete")
            self.event(event="model_not_admitted", model=model, reason="previous model incomplete")
            return False
        est = SERVER_STARTUP_S
        n_e1 = sum(len(load_items(self.runs / d / "items.jsonl")) for d in E1_CORE)
        n_pilot = len(load_items(self.runs / "pilot20" / "items.jsonl"))
        for s in self.a.systems:
            fz = json.loads(self.freeze_path(s, first).read_text(encoding="utf-8"))
            spq = self.spq(first, s) or 60.0
            setup = self.timing.get(f"{first}/{s}", {}).get("setup_s", 0.0)
            est += (len(fz["candidates"]) * n_pilot + 8 + n_e1) * spq + (len(fz["candidates"]) + len(E1_CORE)) * setup
        need = est * MARGIN
        ok = need <= self.seconds_left()
        self.event(event="model_admission", model=model, admitted=ok, estimated_s=round(est),
                   with_margin_s=round(need), seconds_left=round(self.seconds_left()))
        self.log(f"[schedule] {model}: estimated {est / 3600:.1f} h (+20% = {need / 3600:.1f} h), "
                 f"{self.seconds_left() / 3600:.1f} h left -> {'start' if ok else 'not admitted'}")
        return ok

    def run(self) -> int:
        self.event(event="start", args=vars(self.a))
        self.package = self.find_package()
        summary = import_all(self.package, self.runs)
        self.log(f"[import] pilot20 {summary['pilot20']['questions']} questions; E1-core "
                 f"{sum(summary[d]['questions'] for d in E1_CORE)} questions (checksums verified)")
        self.preflight_local()
        serving = self.server.preflight(self.a.models)
        self.provenance(summary, {"environment": serving})
        partial_reason = None
        for i, model in enumerate(self.a.models):
            if self.past_deadline():
                partial_reason = "deadline reached"
                break
            if i > 0 and not self.gemma_admitted(self.a.models[i - 1], model):
                partial_reason = f"{model} not admitted (previous model incomplete or not enough time)"
                break
            self.provenance(summary, {model: self.server.ensure_checkpoint(model)})
            self.server.ensure(model)
            for j, system in enumerate(self.a.systems):
                if self.past_deadline():
                    partial_reason = "deadline reached"
                    break
                self.event(event="stage", model=model, system=system, stage="dev")
                self.dev(model, system, self.a.systems[j + 1:])
                if not self.freeze_path(system, model).exists():
                    partial_reason = "deadline reached during development selection"
                    break
                self.event(event="stage", model=model, system=system, stage="e1")
                self.e1(model, system)
            self.server.stop()
            if partial_reason:
                break
        m = self.deliver(partial_reason or ("deadline reached" if self.past_deadline() else None))
        self.event(event="done", status=m["status"])
        return 0


def load_items_uids(run_dir: Path) -> list[str]:
    return [it.uid for it in load_items(run_dir / "items.jsonl")]


class Lock:
    """One launcher at a time (held by the OS: released automatically if the process dies)."""

    def __init__(self, path: Path):
        self.path = path

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.f = open(self.path, "a+")
        try:
            if os.name == "nt":
                import msvcrt
                self.f.seek(0)
                msvcrt.locking(self.f.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(self.f.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            raise StageError(f"another run_tier_b.py is already running (lock {self.path}). Check "
                             f"runs/tier_b/status.json; only one launcher may run at a time.")
        return self

    def __exit__(self, *exc):
        try:
            if os.name == "nt":
                import msvcrt
                self.f.seek(0)
                msvcrt.locking(self.f.fileno(), msvcrt.LK_UNLCK, 1)
            self.f.close()
        except OSError:
            pass


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--package", help="path to clevrer_docqa_package (found automatically next to the repo)")
    ap.add_argument("--deadline", help=f"ISO time with offset (default {DEADLINE.isoformat()})")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--models", nargs="+", default=MODELS)
    ap.add_argument("--systems", nargs="+", default=SYSTEMS)
    ap.add_argument("--status", action="store_true", help="print the current status and exit")
    ap.add_argument("--runs", default=str(ROOT / "runs"), help=argparse.SUPPRESS)
    ap.add_argument("--mock-server", action="store_true", help=argparse.SUPPRESS)      # tests: no GPU
    ap.add_argument("--dev-limit", type=int, default=None, help=argparse.SUPPRESS)     # tests: fewer pilot questions
    ap.add_argument("--e1-limit", type=int, default=None, help=argparse.SUPPRESS)      # tests: fewer E1 questions
    ap.add_argument("--smoke-per-type", type=int, default=SMOKE_PER_TYPE, help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    if a.status:
        p = Path(a.runs) / "tier_b" / "status.json"
        print(p.read_text(encoding="utf-8") if p.exists() else "no run yet")
        return 0
    pipe = Pipeline(a)
    with Lock(pipe.tb / "launcher.lock"):
        try:
            return pipe.run()
        except KeyboardInterrupt:
            pipe.log("[stop] interrupted: completed answers are saved; run the same command again to resume")
            pipe.event(event="interrupted")
            pipe.server.stop()
            return 130
        except (StageError, ServingError) as e:
            pipe.log(f"[stop] {e}")
            pipe.event(event="stopped", error=str(e))
            pipe.server.stop()
            return 2
        except Exception as e:
            pipe.log(f"[stop] unexpected error: {type(e).__name__}: {e}\n{traceback.format_exc()}")
            pipe.event(event="crashed", error=f"{type(e).__name__}: {e}")
            pipe.server.stop()
            return 1


if __name__ == "__main__":
    sys.exit(main())
